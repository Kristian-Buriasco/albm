export function formatMsg(
  lang: Lang,
  key: keyof I18nDict,
  vars: Record<string, string | number>,
): string {
  let s = t(lang, key);
  for (const [k, v] of Object.entries(vars)) {
    s = s.replace(`{${k}}`, String(v));
  }
  return s;
}

const LOCALE_BY_LANG: Record<Lang, string> = {
  en: 'en-GB',
  nl: 'nl-NL',
  it: 'it-IT',
  fr: 'fr-FR',
  de: 'de-DE',
  es: 'es-ES',
  pt: 'pt-PT',
  ja: 'ja-JP',
  pl: 'pl-PL',
  zh: 'zh-CN',
};

/** BCP-47 locale tag for Date/Intl formatting — one per supported language. */
export function localeForLang(lang: Lang): string {
  return LOCALE_BY_LANG[lang] ?? 'en-GB';
}

export function parseLang(value: string | null | undefined): Lang {
  if (
    value === 'nl' ||
    value === 'it' ||
    value === 'fr' ||
    value === 'de' ||
    value === 'es' ||
    value === 'pt' ||
    value === 'ja' ||
    value === 'pl' ||
    value === 'zh'
  ) {
    return value;
  }
  return 'en';
}
